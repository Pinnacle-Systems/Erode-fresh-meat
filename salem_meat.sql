CREATE TABLE admin_master(
	ADMIN_MASTER_ID BIGINT PRIMARY KEY AUTO_INCREMENT,
	ADMIN_NAME VARCHAR(50) NOT NULL,
	ADMIN_EMAIL VARCHAR(50) UNIQUE NOT NULL,
	ADMIN_PASSWORD VARCHAR(100) NOT NULL,
	CREATED_DATE DATETIME DEFAULT CURRENT_TIMESTAMP,
	STATUS BOOLEAN DEFAULT TRUE NOT NULL
);

CREATE TABLE admin_token
(
	ID BIGINT PRIMARY KEY AUTO_INCREMENT,
	ADMIN_EMAIL VARCHAR(100) NOT NULL,
	TOKEN VARCHAR(80) NOT NULL,
	TIME_MODIFIED TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
	FOREIGN KEY (ADMIN_EMAIL) REFERENCES admin_master(ADMIN_EMAIL)
);

CREATE TABLE category_master
(
	CATEGORY_MASTER_ID BIGINT PRIMARY KEY AUTO_INCREMENT,
	CATEGORY_NAME VARCHAR(50) NOT NULL UNIQUE,
	CATEGORY_IMAGE VARCHAR(100) NOT NULL,
	CATEGORY_DESCRIPTION VARCHAR(100) NOT NULL,
	CATEGORY_STATUS BOOLEAN DEFAULT TRUE NOT NULL,
	CATEGORY_CREATED_DATE DATETIME NOT NULL,
	CATEGORY_CREATED_BY BIGINT NOT NULL,
	FOREIGN KEY (CATEGORY_CREATED_BY) REFERENCES admin_master(ADMIN_MASTER_ID)
);

CREATE TABLE product_master
(
	PRODUCT_MASTER_ID BIGINT PRIMARY KEY AUTO_INCREMENT,
	PRODUCT_NAME VARCHAR(100) NOT NULL UNIQUE,
	PRODUCT_IMAGE VARCHAR(100) NOT NULL,
	PERFECT_FOR VARCHAR(100) NOT NULL,
	GROSS_WEIGHT VARCHAR(100) NOT NULL,
	NET_WEIGHT VARCHAR(100) NOT NULL,
	TOTAL_AMOUNT VARCHAR(50) NOT NULL,
	FINAL_AMOUNT VARCHAR(50) NOT NULL,
	DELIVERY_TIME VARCHAR(100) NOT NULL,
	PRODUCT_STATUS BOOLEAN DEFAULT TRUE NOT NULL,
	PRODUCT_CREATED_DATE DATETIME NOT NULL,
	PRODUCT_CREATED_BY BIGINT NOT NULL,
	CATEGORY_MASTER_ID BIGINT NOT NULL,
	FOREIGN KEY (PRODUCT_CREATED_BY) REFERENCES admin_master(ADMIN_MASTER_ID),
	FOREIGN KEY (CATEGORY_MASTER_ID) REFERENCES category_master(CATEGORY_MASTER_ID)
);

CREATE TABLE order_master
(
	ORDER_MASTER_ID BIGINT PRIMARY KEY AUTO_INCREMENT,
	TRANSACTION_ID VARCHAR(100) NOT NULL UNIQUE,
	CUSTOMER_NAME VARCHAR(100) NOT NULL,
	CUSTOMER_EMAIL VARCHAR(100) NOT NULL,
	CUSTOMER_MOBILE VARCHAR(20) NOT NULL,
	CUSTOMER_STREET_ADDRESS VARCHAR(100) NOT NULL,
	CUSTOMER_TOWN_CITY VARCHAR(100) NOT NULL,
	CUSTOMER_PINCODE VARCHAR(20) NOT NULL,
	ORDER_STATUS INT NOT NULL,
	PAYMENT_METHOD VARCHAR(20) NOT NULL,
	PAYMENT_ID VARCHAR(100)
);

CREATE TABLE ordered_products
(
	ORDERED_PRODUCTS_ID BIGINT PRIMARY KEY AUTO_INCREMENT,
	TRANSACTION_ID VARCHAR(100) NOT NULL,
	PRODUCT_NAME VARCHAR(100) NOT NULL,
	PRODUCT_QUANTITY VARCHAR(100) NOT NULL,
	NUMBER_OF_PRODUCTS VARCHAR(20) NOT NULL,
	PRODUCT_TOTAL_AMOUNT VARCHAR(50) NOT NULL,
	PRODUCT_FINAL_AMOUNT VARCHAR(50) NOT NULL
);


